/**
 * Invariants of the committed fixture tree itself: every fixture must have been
 * produced by the pinned reference, and every suite must actually be consumed by
 * a differential test (otherwise an unused fixture silently rots).
 */

import { readdirSync, readFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vite-plus/test";

import {
    EXPECTED_BUILD123D_VERSION,
    EXPECTED_OCCT_VERSION,
    FIXTURES_DIR,
    readFixtureDocument,
} from "../oracle.ts";

const REPO_ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const PACKAGES_DIR = `${REPO_ROOT}packages`;

// `selftest` is consumed by this directory's own harness tests, not by a package.
const HARNESS_ONLY_SUITES: Record<string, true> = { selftest: true };

const SKIPPED_DIRECTORIES: Record<string, true> = {
    ".occt": true,
    dist: true,
    node_modules: true,
    target: true,
    vendor: true,
};

function suiteNames(): string[] {
    return readdirSync(FIXTURES_DIR)
        .filter(entry => entry.endsWith(".json"))
        .map(entry => entry.slice(0, -".json".length))
        .sort();
}

function testFiles(directory: string): string[] {
    let found: string[] = [];
    for (let entry of readdirSync(directory, { withFileTypes: true })) {
        let path = `${directory}/${entry.name}`;
        if (entry.isDirectory()) {
            if (SKIPPED_DIRECTORIES[entry.name] !== true) found.push(...testFiles(path));
        } else if (entry.name.endsWith(".test.ts")) {
            found.push(path);
        }
    }
    return found;
}

describe("fixture tree", () => {
    it("has at least the harness self-test suite", () => {
        expect(suiteNames()).toContain("selftest");
    });

    it("refuses to load a fixture that is absent", () => {
        expect(() => readFixtureDocument("no-such-suite")).toThrowError(
            /missing fixture reference\/build123d\/fixtures\/no-such-suite\.json/,
        );
    });

    it("was generated by the pinned build123d and OCCT", () => {
        for (let suite of suiteNames()) {
            let document = readFixtureDocument(suite) as { reference: Record<string, string> };
            expect(document.reference, suite).toMatchObject({
                build123d: EXPECTED_BUILD123D_VERSION,
                occt: EXPECTED_OCCT_VERSION,
            });
        }
    });

    it("keeps every asset referenced by a case on disk", () => {
        for (let suite of suiteNames()) {
            let text = readFileSync(`${FIXTURES_DIR}${suite}.json`, "utf8");
            for (let [, relative = ""] of text.matchAll(/"(reference\/[^"]+\.brep)"/g)) {
                expect(statSync(`${REPO_ROOT}${relative}`).isFile(), relative).toBe(true);
            }
        }
    });

    it("has a differential test consuming every suite", () => {
        let sources = testFiles(PACKAGES_DIR).map(path => readFileSync(path, "utf8"));
        for (let suite of suiteNames()) {
            if (HARNESS_ONLY_SUITES[suite] === true) continue;
            let referenced = sources.some(source => source.includes(`oracleSuite("${suite}"`));
            expect(referenced, `no packages/*/tests/**/*.test.ts calls oracleSuite("${suite}")`) //
                .toBe(true);
        }
    });
});
