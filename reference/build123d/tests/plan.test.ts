import { describe, expect, it } from "vite-plus/test";

import type { OracleImplementation } from "../oracle.ts";

import { EXPECTED_BUILD123D_VERSION, EXPECTED_OCCT_VERSION, planOracleSuite } from "../oracle.ts";

const PINNED_REFERENCE = {
    build123d: EXPECTED_BUILD123D_VERSION,
    ocp: "8.0.1.1.0",
    occt: EXPECTED_OCCT_VERSION,
    python: "3.13.17",
};

let noop: OracleImplementation = () => {};

function document(cases: Record<string, unknown>, reference: unknown = PINNED_REFERENCE): unknown {
    return { suite: "demo", reference, cases };
}

describe("planOracleSuite", () => {
    it("plans one test per matched case, in name order", () => {
        let plan = planOracleSuite(document({ "b/two": { v: 2 }, "a/one": { v: 1 } }), {
            "a/one": noop,
            "b/two": noop,
        });

        expect(plan.errors).toEqual([]);
        expect(plan.tests.map(test => test.name)).toEqual(["a/one", "b/two"]);
    });

    it("hands the implementation a case view naming the suite and case", () => {
        let plan = planOracleSuite(document({ "a/one": { v: 1 } }), { "a/one": noop });

        expect(plan.tests[0]?.expected).toEqual({
            suite: "demo",
            name: "a/one",
            path: "",
            data: { v: 1 },
        });
    });

    it("fails when a fixture case has no implementation", () => {
        let plan = planOracleSuite(document({ "a/one": {}, "b/two": {} }), { "a/one": noop });

        expect(plan.tests.map(test => test.name)).toEqual(["a/one"]);
        expect(plan.errors).toEqual(["demo/b/two: fixture case has no implementation"]);
    });

    it("fails when an implementation has no fixture case", () => {
        let plan = planOracleSuite(document({ "a/one": {} }), { "a/one": noop, "b/two": noop });

        expect(plan.errors).toHaveLength(1);
        expect(plan.errors[0]).toContain("demo/b/two: implementation has no fixture case");
    });

    it("fails when the fixture was generated by another reference version", () => {
        let stale = { ...PINNED_REFERENCE, build123d: "0.12.0", occt: "7.8.1" };
        let plan = planOracleSuite(document({ "a/one": {} }, stale), { "a/one": noop });

        expect(plan.errors).toHaveLength(2);
        expect(plan.errors[0]).toContain('build123d "0.12.0"');
        expect(plan.errors[0]).toContain(`pins "${EXPECTED_BUILD123D_VERSION}"`);
        expect(plan.errors[1]).toContain('occt "7.8.1"');
        expect(plan.errors[1]).toContain(`pins "${EXPECTED_OCCT_VERSION}"`);
    });

    it("fails when the reference header is missing", () => {
        let plan = planOracleSuite({ suite: "demo", cases: { "a/one": {} } }, { "a/one": noop });

        expect(plan.errors[0]).toContain('fixture has no "reference" header');
    });

    it("fails on a malformed document instead of registering nothing", () => {
        expect(planOracleSuite(null, {})).toEqual({
            tests: [],
            errors: ["fixture is object, expected an object"],
        });
        expect(planOracleSuite({ cases: {} }, {}).errors).toEqual(['fixture has no "suite" name']);
        expect(planOracleSuite({ suite: "demo", cases: [] }, {}).errors).toContain(
            'demo: fixture has no "cases" object',
        );
        expect(planOracleSuite(document({}), {}).errors).toContain(
            "demo: fixture contains no cases",
        );
        expect(planOracleSuite(document({ "a/one": 7 }), { "a/one": noop }).errors).toEqual([
            "demo/a/one: case is not an object",
        ]);
    });
});
