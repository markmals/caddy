//! Turns the binding model into crate files: one cxx bridge + C++ header per OCCT package.

mod collections;
mod functions;
mod helpers;
mod item;
mod module;
mod types;

use std::collections::{BTreeMap, BTreeSet};

use crate::model::{Bindings, Skipped, Ty};

use self::{functions::Context, item::Item, module::Module};

pub const GENERATED_MARKER: &str = "Generated by occt-bindgen";

/// Relative path -> file content for everything the generator owns.
pub type Files = BTreeMap<String, String>;

fn module<'a>(modules: &'a mut BTreeMap<String, Module>, name: &str) -> &'a mut Module {
    modules.entry(name.to_owned()).or_insert_with(|| Module::new(name))
}

pub fn emit(bindings: &Bindings, occt_version: &str) -> (Files, Vec<Skipped>) {
    let mut skipped = bindings.skipped.clone();
    let mut modules: BTreeMap<String, Module> = BTreeMap::new();

    for enumeration in &bindings.enums {
        module(&mut modules, &enumeration.module).enums.push(enumeration.clone());
    }
    for collection in &bindings.collections {
        let target = module(&mut modules, &collection.module);
        target.declare(&collection.name);
        if collection.is_handle {
            target.declare(&format!("Handle_{}", collection.name));
        }
        match collections::collection_items(collection) {
            Ok(items) => target.items.extend(items),
            Err(reason) => skipped.push(Skipped { symbol: collection.name.clone(), reason }),
        }
    }

    let reserved_names: BTreeSet<String> = bindings
        .classes
        .iter()
        .flat_map(|class| [class.name.clone(), format!("Handle_{}", class.name)])
        .chain(bindings.collections.iter().map(|c| c.name.clone()))
        .chain(bindings.enums.iter().map(|e| e.name.clone()))
        .collect();
    let reserved = |name: &str| reserved_names.contains(name);
    let copyable = |ty: &Ty| match ty {
        Ty::Handle(_) => true,
        Ty::Class(name) => bindings.class(name).is_some_and(|class| class.clone),
        _ => false,
    };

    for class in &bindings.classes {
        let context = Context { class, reserved: &reserved, copyable: &copyable };
        let target = module(&mut modules, &class.module);
        if !class.is_namespace {
            target.declare(&class.name);
        }
        if class.is_transient {
            target.declare(&format!("Handle_{}", class.name));
        }
        for function in class.constructors.iter().chain(&class.methods) {
            match functions::emit_function(function, &context) {
                Ok(item) => target.items.push(item),
                Err(reason) => skipped.push(Skipped {
                    symbol: format!("{}::{}", class.name, function.rust_name),
                    reason,
                }),
            }
        }
        target.items.extend(helpers::class_helpers(class, bindings));
    }

    let owned_anywhere: BTreeSet<String> = modules
        .values()
        .flat_map(|m| m.items.iter().flat_map(|i: &Item| i.owned.iter().cloned()))
        .collect();
    let owner_module = |bridge_type: &str| -> String {
        if bridge_type == types::STREAM_TYPE {
            return types::STREAM_MODULE.to_owned();
        }
        let base = bridge_type.strip_prefix("Handle_").unwrap_or(bridge_type);
        bindings.module_of(base).map(str::to_owned).unwrap_or_default()
    };
    let header_of = |name: &str| -> String {
        bindings
            .class(name)
            .map(|c| c.header.clone())
            .or_else(|| bindings.collection(name).map(|c| c.header.clone()))
            .or_else(|| bindings.enums.iter().find(|e| e.name == name).map(|e| e.header.clone()))
            .unwrap_or_else(|| format!("{name}.hxx"))
    };

    let mut files = Files::new();
    for module in modules.values() {
        let rust = module.rust_source(&owned_anywhere, &owner_module, occt_version);
        let cpp = module.cpp_header(&header_of, occt_version);
        files.insert(format!("src/{}.rs", module.name), rust);
        files.insert(format!("include/generated/{}.hxx", module.name), cpp);
    }
    files.insert(
        "include/generated/handles.hxx".into(),
        handles_header(bindings, &header_of, occt_version),
    );
    files.insert(format!("src/{}.rs", types::STREAM_MODULE), stream_source(occt_version));
    let mut module_names: BTreeSet<&String> = modules.keys().collect();
    let stream_module = types::STREAM_MODULE.to_owned();
    module_names.insert(&stream_module);
    files.insert("src/lib.rs".into(), lib_source(module_names.into_iter(), occt_version));
    files.insert("occt-toolkits.txt".into(), bindings.toolkits.join("\n") + "\n");
    skipped.sort_by(|a, b| a.symbol.cmp(&b.symbol).then(a.reason.cmp(&b.reason)));
    skipped.dedup_by(|a, b| a.symbol == b.symbol && a.reason == b.reason);
    (files, skipped)
}

/// Built-in bridge for `OcctStream` (defined in bindings_common.hxx), which stands in for the
/// `std::ostream` / `std::istream` parameters of OCCT's stream-based IO.
fn stream_source(occt_version: &str) -> String {
    let t = types::STREAM_TYPE;
    format!(
        "//! {GENERATED_MARKER} from OCCT {occt_version} headers. Do not edit; see bindings.toml.\n\
         pub use inner::*;\n\n#[rustfmt::skip]\n#[cxx::bridge]\nmod inner {{\n    unsafe extern \"C++\" {{\n        \
         include!(\"opencascade-sys/include/bindings_common.hxx\");\n\n        \
         /// In-memory binary `std::stringstream` accepted wherever OCCT takes a stream.\n        \
         type {t};\n        \
         fn {t}_new() -> UniquePtr<{t}>;\n        \
         fn {t}_from_bytes(bytes: &[u8]) -> UniquePtr<{t}>;\n        \
         fn {t}_to_bytes(stream: &{t}) -> Vec<u8>;\n    }}\n\n    impl UniquePtr<{t}> {{}}\n}}\n"
    )
}

fn handles_header(
    bindings: &Bindings,
    header_of: &dyn Fn(&str) -> String,
    occt_version: &str,
) -> String {
    let names: Vec<&str> = bindings
        .classes
        .iter()
        .filter(|c| c.is_transient)
        .map(|c| c.name.as_str())
        .chain(bindings.collections.iter().filter(|c| c.is_handle).map(|c| c.name.as_str()))
        .collect();
    let includes: BTreeSet<String> = names.iter().map(|n| header_of(n)).collect();
    let mut out = format!(
        "// {GENERATED_MARKER} from OCCT {occt_version} headers. Do not edit.\n#pragma once\n#include <Standard_Handle.hxx>\n"
    );
    for header in includes {
        out.push_str(&format!("#include <{header}>\n"));
    }
    out.push('\n');
    for name in names {
        out.push_str(&format!("typedef opencascade::handle<{name}> Handle_{name};\n"));
    }
    out
}

fn lib_source<'a>(modules: impl Iterator<Item = &'a String>, occt_version: &str) -> String {
    let mut out = format!(
        "//! {GENERATED_MARKER} from OCCT {occt_version} headers. Do not edit; see bindings.toml.\n\
         //!\n\
         //! One module per OCCT package. Every function that can reach OCCT returns\n\
         //! `Result`, so C++ exceptions surface as `cxx::Exception` instead of aborting.\n\
         #![allow(non_snake_case, non_camel_case_types, non_upper_case_globals)]\n\
         #![allow(clippy::all)]\n\n"
    );
    for module in modules {
        out.push_str(&format!("pub mod {module};\n"));
    }
    out
}
