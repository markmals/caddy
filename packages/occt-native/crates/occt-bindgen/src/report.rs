//! `bindings-report.md`: what was generated and every member that was skipped, with reasons.

use std::collections::BTreeMap;

use crate::model::{Bindings, Skipped};

pub fn render(bindings: &Bindings, skipped: &[Skipped], occt_version: &str) -> String {
    let functions: usize =
        bindings.classes.iter().map(|c| c.constructors.len() + c.methods.len()).sum();
    let mut out = format!(
        "# opencascade-sys binding report\n\n\
         Generated by occt-bindgen from OCCT {occt_version} headers. Do not edit; regenerate with \
         `pnpm --filter @roonieone/occt-native generate:bindings`.\n\n\
         | Item | Count |\n| --- | --- |\n\
         | Classes | {} |\n| Enums | {} |\n| Collections | {} |\n| Constructors and members | {functions} |\n\
         | Skipped members | {} |\n| Linked toolkits | {} |\n\n",
        bindings.classes.len(),
        bindings.enums.len(),
        bindings.collections.len(),
        skipped.len(),
        bindings.toolkits.len(),
    );

    let mut missing: BTreeMap<&str, usize> = BTreeMap::new();
    for entry in skipped {
        if let Some(name) = missing_type(&entry.reason) {
            *missing.entry(name).or_default() += 1;
        }
    }
    let mut by_count: Vec<_> = missing.into_iter().collect();
    by_count.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    out.push_str("## Types blocking the most members\n\nAllowlisting these in `bindings.toml` would unlock the skipped members that use them.\n\n| Type | Members |\n| --- | --- |\n");
    for (name, count) in by_count.iter().take(40) {
        out.push_str(&format!("| `{name}` | {count} |\n"));
    }

    out.push_str("\n## Skipped members\n\n| Member | Reason |\n| --- | --- |\n");
    for entry in skipped {
        out.push_str(&format!(
            "| `{}` | {} |\n",
            entry.symbol.replace('|', "\\|"),
            entry.reason.replace('|', "\\|")
        ));
    }
    out
}

fn missing_type(reason: &str) -> Option<&str> {
    let start = reason.find('`')? + 1;
    let end = start + reason[start..].find('`')?;
    reason.contains("not allowlisted").then(|| &reason[start..end])
}
